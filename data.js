  WE.binIndex = function (ind, v) {
    var b = WE.INDICATORS[ind].bins, i = 0;
    while (i < b.length && v >= b[i]) i++;
    return i;
  };
  WE.colorFor = function (ind, v) {
    if (v == null || isNaN(v)) return null;
    return WE.INDICATORS[ind].pal[WE.binIndex(ind, v)];
  };

  /* 排名（由大到小），可依區域篩選 */
  WE.ranking = function (ind, year, region) {
    return WE.COUNTRIES
      .filter(function (c) { return !region || region === 'all' || c.region === region; })
      .map(function (c) { return { c: c, v: WE.value(c, ind, year) }; })
      .sort(function (a, b) { return b.v - a.v; });
  };
  WE.rankOf = function (iso, ind, year) {
    var r = WE.ranking(ind, year, 'all');
    for (var i = 0; i < r.length; i++) if (r[i].c.iso === iso) return i + 1;
    return null;
  };

